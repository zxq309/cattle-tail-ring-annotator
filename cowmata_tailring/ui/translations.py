def _coverage() -> None:
    """Report catalogue coverage against the strings actually used in the code."""
    import ast
    import re
    from pathlib import Path

    cjk = re.compile(r"[\u4e00-\u9fff]")
    root = Path(__file__).resolve().parent.parent
    found: set[str] = set()
    for path in root.rglob("*.py"):
        if "model_runtime" in path.parts or path.name == "translations.py":
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        docs = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.Module, ast.FunctionDef, ast.ClassDef)):
                first = node.body[0] if node.body else None
                if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant):
                    docs.add(id(first.value))
        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                if id(node) not in docs and cjk.search(node.value):
                    found.add(node.value)
    done = found & ZH_TO_EN.keys()
    print(f"catalogue entries : {len(ZH_TO_EN)}")
    print(f"strings in code   : {len(found)}")
    print(f"translated        : {len(done)} ({100 * len(done) / max(len(found), 1):.1f}%)")
    print(f"untranslated      : {len(found - ZH_TO_EN.keys())}")


